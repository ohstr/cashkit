#!/usr/bin/env node
// Generates src/core/idnaData.ts from the Unicode 15.0.0 data files that
// golang.org/x/net/idna (and so nmilat) is built on: the UTS #46 mapping
// table, the derived bidi classes and the derived general categories.
// Pinned by URL and SHA-256; any other content is refused, so a rerun
// reproduces the committed file byte for byte.
//
//   node tools/gen-idna-tables.mjs            # downloads the three files
//   node tools/gen-idna-tables.mjs <dir>      # reads them from <dir>
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const FILES = {
  'IdnaMappingTable.txt': ['https://www.unicode.org/Public/idna/15.0.0/IdnaMappingTable.txt', 'cc8522199541d60326a42a8f91f8748fd15630a42502dd2cf4878e81e2066ead'],
  'DerivedBidiClass.txt': ['https://www.unicode.org/Public/15.0.0/ucd/extracted/DerivedBidiClass.txt', '4841f2090c2dbc592d3ce43bb74c2191b3da50fb9a0d00274f1448c202851b02'],
  'DerivedGeneralCategory.txt': ['https://www.unicode.org/Public/15.0.0/ucd/extracted/DerivedGeneralCategory.txt', 'fe29a45c0882500e591140aaa5c4f5067e6a5d746806148af34400c48b9c06f9'],
}

async function source(name) {
  const [url, sum] = FILES[name]
  const dir = process.argv[2]
  const text = dir !== undefined ? readFileSync(join(dir, name), 'utf8') : await (await fetch(url)).text()
  const got = createHash('sha256').update(text).digest('hex')
  if (got !== sum) throw new Error(`${name}: sha256 ${got}, want ${sum}`)
  return text
}

/** Data lines as [first, last, fields...]. */
function rows(text) {
  const out = []
  for (const raw of text.split('\n')) {
    const line = raw.replace(/#.*/, '').trim()
    if (line === '') continue
    const f = line.split(';').map((x) => x.trim())
    const [a, b] = f[0].split('..').map((x) => parseInt(x, 16))
    out.push([a, b ?? a, ...f.slice(1)])
  }
  return out
}

/** Sorted, merged [first, last] ranges, as a compact delta string: base-36 pairs (gap, length - 1). */
function encode(ranges) {
  ranges.sort((x, y) => x[0] - y[0])
  const merged = []
  for (const [a, b] of ranges) {
    const last = merged.at(-1)
    if (last !== undefined && a <= last[1] + 1) last[1] = Math.max(last[1], b)
    else merged.push([a, b])
  }
  let prev = 0
  const parts = []
  for (const [a, b] of merged) {
    parts.push(`${(a - prev).toString(36)}.${(b - a).toString(36)}`)
    prev = b + 1
  }
  return { text: parts.join(','), count: merged.length }
}

const idna = rows(await source('IdnaMappingTable.txt'))
// Valid under UTS #46 non-transitional lookup with UseSTD3ASCIIRules: `valid`
// (NV8 and XV8 included, as Go's idna treats them). Deviations, mapped,
// ignored, disallowed and the STD3 classes are not.
const valid = encode(idna.filter((r) => r[2] === 'valid').map((r) => [r[0], r[1]]))

const bidiRows = rows(await source('DerivedBidiClass.txt'))
const BIDI = ['R', 'AL', 'AN', 'EN', 'ES', 'CS', 'ET', 'ON', 'BN', 'NSM']
const bidi = Object.fromEntries(BIDI.map((c) => [c, encode(bidiRows.filter((r) => r[2] === c).map((r) => [r[0], r[1]]))]))

const gc = rows(await source('DerivedGeneralCategory.txt'))
const marks = encode(gc.filter((r) => r[2] === 'Mn' || r[2] === 'Mc' || r[2] === 'Me').map((r) => [r[0], r[1]]))

const out = `// Generated by tools/gen-idna-tables.mjs from Unicode 15.0.0 (the UTS #46
// mapping table, DerivedBidiClass.txt and DerivedGeneralCategory.txt). Do not
// edit: rerun the generator.
//
${Object.entries(FILES).map(([n, [, sum]]) => `// ${n} sha256 ${sum}`).join('\n')}
//
// Each table is a list of code point ranges: base-36 pairs "gap.span", the gap
// from the end of the previous range plus one, the span the length minus one.

/** UTS #46 status \`valid\` (NV8 and XV8 included): ${valid.count} ranges. */
export const IDNA_VALID = '${valid.text}'

/** Bidi classes other than L (the default): ${BIDI.map((c) => `${c} ${bidi[c].count}`).join(', ')} ranges. */
export const BIDI_CLASSES: Readonly<Record<string, string>> = {
${BIDI.map((c) => `  ${c}: '${bidi[c].text}',`).join('\n')}
}

/** General category Mark (Mn, Mc, Me): ${marks.count} ranges. */
export const MARKS = '${marks.text}'
`
writeFileSync(new URL('../src/core/idnaData.ts', import.meta.url), out)
console.log(`idnaData.ts: valid ${valid.count}, marks ${marks.count}, bidi ${BIDI.map((c) => bidi[c].count).join('/')}`)
